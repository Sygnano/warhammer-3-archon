"""Embed archon_native.dll as a Lua 5.1 string blob (chunked, escaped), the way memreader / Agus224 do.

Writes a Lua file that returns { name=..., version=..., size=N, sha256=..., chunks={...} }. Each chunk is
a <=4096-byte Lua string literal; every byte that is not printable ASCII (and not the delimiter) is written
as a 3-digit \\ddd escape, which Lua 5.1 decodes back to the exact byte.

Usage: python -I dll_to_lua.py <archon_native.dll> <out.lua> <module_name> <version>
"""
import sys, hashlib

def esc(chunk):
    out = []
    for byte in chunk:
        if byte == 0x5C:            # backslash
            out.append("\\\\")
        elif byte == 0x22:          # double quote
            out.append("\\\"")
        elif 0x20 <= byte < 0x7F:
            out.append(chr(byte))
        else:
            out.append("\\%03d" % byte)  # ALWAYS 3-digit \ddd: Lua reads at most 3 digits greedily, so
                                         # zero-padding avoids merging with a following literal digit.
    return "".join(out)

def main():
    dll, out, name, version = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
    data = open(dll, "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    step = 4096
    parts = [data[i:i+step] for i in range(0, len(data), step)]
    with open(out, "w", newline="\n") as f:
        f.write("-- GENERATED by tools/dll_to_lua.py. Do not edit by hand.\n")
        f.write("-- archon_native.dll embedded as an escaped Lua string blob.\n")
        f.write("return {\n")
        f.write("  name = %r,\n" % name)
        f.write("  version = %r,\n" % version)
        f.write("  size = %d,\n" % len(data))
        f.write("  sha256 = %r,\n" % sha)
        f.write("  chunks = {\n")
        for p in parts:
            f.write('    "%s",\n' % esc(p))
        f.write("  },\n")
        f.write("}\n")
    print("wrote %s: %d bytes, %d chunks, sha256=%s" % (out, len(data), len(parts), sha))

if __name__ == "__main__":
    main()
